"""Draft a starter contract from an observed corpus.

The output is a draft for human review, not a guarantee of correctness.
"""

from __future__ import annotations

import math
from typing import Any

import polars as pl
import yaml

ID_CANDIDATES = ("chunk_id", "id", "_id", "uuid")
TEXT_CANDIDATES = ("text", "content", "chunk", "page_content", "body")
ACL_CANDIDATES = ("acl", "access", "classification", "visibility", "permissions")
VECTOR_CANDIDATES = ("embedding", "vector", "embeddings")
SOURCE_CANDIDATES = ("source", "url", "uri", "path", "page", "doc_title", "title")


def _first(columns: list[str], candidates: tuple[str, ...]) -> str | None:
    lower = {c.lower(): c for c in columns}
    return next((lower[c] for c in candidates if c in lower), None)


def suggest_contract(df: pl.DataFrame, margin: float = 0.2) -> dict[str, Any]:
    cols = df.columns
    rag: list[dict[str, Any]] = []
    id_col = _first(cols, ID_CANDIDATES)
    text_col = _first(cols, TEXT_CANDIDATES)
    acl_col = _first(cols, ACL_CANDIDATES)
    vec_col = _first(cols, VECTOR_CANDIDATES)
    sources = [c for c in cols if c.lower() in SOURCE_CANDIDATES]

    required = [c for c in (id_col, "doc_id" if "doc_id" in cols else None, text_col, acl_col) if c]
    if required:
        rag.append({"test": "required_fields", "fields": required})
    if id_col:
        rag.append({"test": "unique_ids", "column": id_col})
    if text_col:
        lengths = df[text_col].fill_null("").str.len_chars()
        p1 = lengths.quantile(0.01) or 0
        p99 = lengths.quantile(0.99) or 0
        rag.append(
            {
                "test": "chunk_length",
                "column": text_col,
                "min_chars": max(1, math.floor(p1 * (1 - margin))),
                "max_chars": max(1, math.ceil(p99 * (1 + margin))),
            }
        )
        rag.append({"test": "duplicate_text", "column": text_col})
        rag.append({"test": "pii_patterns", "column": text_col, "severity": "warn"})
    if acl_col:
        allowed = sorted(str(v) for v in df[acl_col].drop_nulls().unique().to_list())
        item: dict[str, Any] = {"test": "acl_required", "column": acl_col}
        if allowed:
            item["allowed"] = allowed
        rag.append(item)
    if vec_col and isinstance(df.schema[vec_col], (pl.List, pl.Array)):
        dims = df[vec_col].list.len().drop_nulls()
        if dims.len():
            rag.append({"test": "embedding_dim", "column": vec_col, "dim": int(dims.mode().sort()[0])})
    if sources:
        rag.append({"test": "source_metadata", "fields": sources, "max_null_pct": 0.0})

    floor = max(1, math.floor(df.height * (1 - margin)))
    wimsey_tests = [{"test": "row_count_should", "be_greater_than_or_equal_to": floor}]
    return {"version": 1, "rag": rag, "wimsey": wimsey_tests}


def suggest_yaml(df: pl.DataFrame, margin: float = 0.2) -> str:
    header = "# Draft contract generated by `corpusgate suggest`.\n# Review every threshold before using it as a CI gate.\n"
    return header + yaml.safe_dump(suggest_contract(df, margin), sort_keys=False, default_flow_style=None)
