"""Report renderers: console, markdown, json."""

from __future__ import annotations

import json
import sys

from corpusgate.runner import Report

OK, FAIL, WARN = "ok", "fail", "warn"
_LABEL = {OK: "PASS", FAIL: "FAIL", WARN: "WARN"}
_ICON = {OK: "✅", FAIL: "❌", WARN: "⚠️"}
_ORDER = {FAIL: 0, WARN: 1, OK: 2}
_STYLE = {OK: "green", FAIL: "bold red", WARN: "yellow"}


def _limit_text(limit: object, encoding: str | None = None) -> str:
    """Render a limit, falling back to ASCII when the target cannot encode '≤'."""
    if limit is None:
        return ""
    glyph = "≤"
    if encoding:
        try:
            glyph.encode(encoding)
        except (UnicodeEncodeError, LookupError):
            glyph = "<="
    return f"{glyph} {limit}"


def _status(o) -> str:
    if o.passed:
        return OK
    return FAIL if o.severity == "error" else WARN


def _headline(report: Report) -> str:
    verdict = "PASSED" if report.passed else "FAILED"
    return (
        f"Contract {verdict}: {len(report.outcomes)} checks on {report.rows} rows "
        f"· {len(report.errors)} error(s) · {len(report.warnings)} warning(s)"
    )


def render_json(report: Report) -> str:
    return json.dumps(report.to_dict(), indent=2, default=str)


def render_markdown(report: Report, encoding: str | None = None) -> str:
    lines = [
        "## RAG corpus contract report",
        "",
        f"**{_ICON[OK] if report.passed else _ICON[FAIL]} {_headline(report)}**",
        "",
        f"Data: `{report.data}`",
        "",
        "| Status | Check | Observed | Limit | What it means |",
        "|---|---|---|---|---|",
    ]
    for o in sorted(report.outcomes, key=lambda o: _ORDER[_status(o)]):
        s = _status(o)
        observed = "" if o.passed else str(o.observed)
        limit = "" if o.limit is None else _limit_text(o.limit, encoding)
        lines.append(f"| {_ICON[s]} {_LABEL[s]} | `{o.probe}` | {observed} | {limit} | {o.description} |")
    lines += ["", "<sub>Generated by corpusgate</sub>", ""]
    return "\n".join(lines)


def render_console(report: Report) -> None:
    from rich.console import Console
    from rich.table import Table

    console = Console()
    encoding = getattr(sys.stdout, "encoding", None)
    table = Table(title=f"RAG corpus contract · {report.data}", show_lines=False)
    for col in ("Status", "Check", "Observed", "Limit", "What it means"):
        table.add_column(col, overflow="fold")
    for o in sorted(report.outcomes, key=lambda o: _ORDER[_status(o)]):
        s = _status(o)
        table.add_row(
            f"[{_STYLE[s]}]{_LABEL[s]}[/]",
            o.probe,
            "" if o.passed else str(o.observed),
            "" if o.limit is None else _limit_text(o.limit, encoding),
            o.description,
        )
    console.print(table)
    console.print(f"[{'green' if report.passed else 'bold red'}]{_headline(report)}[/]")
